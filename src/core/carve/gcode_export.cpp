std::string generateGcode(const MultiPassToolpath& toolpath,
                          const ToolpathConfig& config,
                          const std::string& modelName,
                          const std::string& toolName,
                          cnc::SendUnits units)
{
    std::ostringstream out;

    writeHeader(out, modelName, toolName, config, units);
    writePreamble(out, units);

    // Safe Z retract before starting
    out << "G0 Z" << fmt(cnc::toSendLength(config.safeZMm, units)) << "\n";

    f32 lastFeedRate = -1.0f;
    bool hasPosition = false;
    Vec3 lastPosition{0.0f};
    bool lastRapid = true;

    // Clearing pass first (if present)
    if (!toolpath.clearing.points.empty()) {
        writeToolpath(out, toolpath.clearing, config, "Clearing pass",
                      lastFeedRate, hasPosition, lastPosition, lastRapid, units);
    }

    if (toolpath.requiresToolChange &&
        !toolpath.clearing.points.empty() &&
        !toolpath.finishing.points.empty()) {
        writeToolChangeBoundary(out, toolpath, config,
                                lastFeedRate, hasPosition,
                                lastPosition, lastRapid, units);
    }

    // Finishing pass
    if (!toolpath.finishing.points.empty()) {
        writeToolpath(out, toolpath.finishing, config, "Finishing pass",
                      lastFeedRate, hasPosition, lastPosition, lastRapid, units);
    }

    writeFooter(out, config.safeZMm, units);

    return out.str();
}

bool exportGcode(const std::string& path,
                 const MultiPassToolpath& toolpath,
                 const ToolpathConfig& config,
                 const std::string& modelName,
                 const std::string& toolName,
                 cnc::SendUnits units)
{
    std::string gcode = generateGcode(toolpath, config, modelName, toolName, units);

    std::ofstream file(path, std::ios::out | std::ios::trunc);
    if (!file.is_open()) return false;

    file << gcode;
    return file.good();
}

